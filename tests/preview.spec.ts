import {expect, test} from '@playwright/test'

test('Arabic language toggle keeps the equivalent page and supports mobile navigation', async ({page}) => {
  await page.setViewportSize({width:390,height:844})
  await page.goto('/en/pro-services/')
  await page.getByRole('link',{name:'العربية'}).click()
  await expect(page).toHaveURL(/\/ar\/pro-services\/$/)
  await expect(page.locator('html')).toHaveAttribute('dir','rtl')
  await expect(page.locator('html')).toHaveAttribute('lang','ar')
  const menu = page.getByRole('button',{name:'القائمة'})
  await expect(menu).toHaveAttribute('aria-expanded','false')
  await menu.click()
  await expect(page.getByRole('navigation',{name:'القائمة الرئيسية'})).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
})

test('quiz hands off preferences and a sample consultation is accepted', async ({page}) => {
  await page.goto('/en/')
  await page.getByRole('link',{name:'Find Your Setup Route'}).click()
  await page.getByLabel('Mainly in the UAE local market').check()
  await page.getByLabel('Trading or retail').check()
  await page.getByLabel('Yes',{exact:true}).check()
  await page.getByRole('button',{name:'See my recommendation'}).click()
  await expect(page.getByRole('heading',{name:'Explore mainland setup'})).toBeVisible()
  await page.getByRole('link',{name:'Share preferences with a consultation request'}).click()
  await expect(page.getByLabel('Service interest')).toHaveValue('business-setup/mainland')
  await expect(page.locator('#quiz-context')).toBeVisible()
  await page.getByLabel('Name',{exact:true}).fill('Sample Only')
  await page.getByLabel('Email address').fill('sample@example.com')
  await page.getByRole('checkbox').check()
  await page.getByRole('button',{name:'Send Inquiry'}).click()
  await expect(page.getByRole('status')).toHaveText('Sample inquiry accepted by the preview endpoint.')
  await expect(page.locator('#quiz-context')).toBeHidden()
})

test('lead endpoint rejects invalid submissions and the form can retry', async ({page,request}) => {
  const invalid = await request.post('/api/lead',{form:{name:'Sample'},headers:{Origin:'http://127.0.0.1:4321'}})
  expect(invalid.status()).toBe(422)
  const wrongOrigin = await request.post('/api/lead',{form:{name:'Sample'},headers:{Origin:'https://example.com'}})
  expect(wrongOrigin.status()).toBe(403)

  await page.goto('/en/contact/')
  await page.route('**/api/lead',route => route.fulfill({status:503,json:{accepted:false}}),{times:1})
  await page.getByLabel('Name',{exact:true}).fill('Sample Only')
  await page.getByLabel('Email address').fill('sample@example.com')
  await page.getByRole('checkbox').check()
  await page.getByRole('button',{name:'Send Inquiry'}).click()
  await expect(page.getByRole('status')).toContainText('try again')
  await expect(page.getByLabel('Email address')).toHaveValue('sample@example.com')
  await page.getByRole('button',{name:'Send Inquiry'}).click()
  await expect(page.getByRole('status')).toContainText('Sample inquiry accepted')
})
